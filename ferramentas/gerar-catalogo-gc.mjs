// Builds the list of title templates the panel offers (painel/gc/catalogo.js) from the descriptors in painel/gc:
// one .json next to each .html, with id, name, collection and fields. Also makes sure every template loads the
// shared gc.js. With a folder as argument, copies the templates from there first, e.g.
//   node gerar-catalogo-gc.mjs ..\..\FreeMix\assets\graphics
// To add a template: put its .html and .json in a folder under painel/gc and run this again.
import { cpSync, existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const gc = fileURLToPath(new URL("../painel/gc/", import.meta.url));
if (process.argv[2]) {
  const from = resolve(process.argv[2]);
  for (const dir of readdirSync(from).filter((d) => statSync(join(from, d)).isDirectory())) cpSync(join(from, dir), join(gc, dir), { recursive: true });
}
const list = [];

function scanDir(currentDir, relPrefix = "") {
  for (const entry of readdirSync(currentDir).sort()) {
    const fullPath = join(currentDir, entry);
    const stat = statSync(fullPath);
    if (stat.isDirectory()) {
      scanDir(fullPath, relPrefix ? `${relPrefix}/${entry}` : entry);
    } else if (entry.endsWith(".json") && !entry.endsWith("manifest.json") && !entry.endsWith("package.json")) {
      try {
        const d = JSON.parse(readFileSync(fullPath, "utf8"));
        if (!d.id || !d.fields || !d.htmlFile) continue;
        const html = join(currentDir, d.htmlFile);
        if (!existsSync(html)) { console.log(`sem o arquivo ${relPrefix}/${d.htmlFile}: ignorado`); continue; }
        let page = readFileSync(html, "utf8");
        if (!page.includes("window.GC")) { console.log(`${relPrefix}/${d.htmlFile} não define window.GC: ignorado`); continue; }
        const scriptRel = "../".repeat(relPrefix.split("/").length) + "gc.js";
        if (!page.includes('gc.js')) {
          page = page.replace(/<\/body>/i, `<script src="${scriptRel}"></script>\n</body>`);
          writeFileSync(html, page);
        }
        list.push({
          id: d.id,
          name: d.name,
          collection: d.collection || "Personalizado",
          category: d.category || "Geral",
          thumbnail: d.thumbnail ? (relPrefix ? `${relPrefix}/${d.thumbnail}` : d.thumbnail) : "",
          file: relPrefix ? `${relPrefix}/${d.htmlFile}` : d.htmlFile,
          fields: d.fields || []
        });
      } catch (err) {
        // Ignorar arquivos JSON inválidos
      }
    }
  }
}

scanDir(gc);

writeFileSync(join(gc, "catalogo.js"), "// Generated by ferramentas/gerar-catalogo-gc.mjs. Do not edit by hand.\nwindow.GC_CATALOG = " + JSON.stringify(list, null, 1) + ";\n");
console.log(`${list.length} modelos: ${list.map((x) => x.collection + " / " + x.name).join("; ")}`);
